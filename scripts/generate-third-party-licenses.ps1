<#
.SYNOPSIS
    Generates THIRD-PARTY-LICENSES.txt: the full license text of every NuGet package Philter Desktop
    restores, plus the notices files those packages ship and the bundled model's license.

.DESCRIPTION
    For each package (from PhilterDesktop\obj\project.assets.json, so restore first):
      - a license file shipped in the package is used verbatim;
      - otherwise the package's SPDX license is taken from scripts\license-texts (MIT and BSD-3-Clause
        templates get the package's copyright line from NOTICE); long licenses shared by many packages
        (Apache-2.0, MPL, MS-PL) are printed once at the end and referenced;
      - NOTICE / THIRD-PARTY-NOTICES / ThirdPartyNotices files in the package are appended.
    Identical texts are printed once. Output is deterministic, so -Check can verify the committed file.

.PARAMETER Check
    Don't write; exit 1 if the committed file differs from what would be generated.
#>
[CmdletBinding()]
param(
    [string]$AssetsPath,
    [string]$OutPath,
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
if (-not $AssetsPath) { $AssetsPath = Join-Path $repo 'PhilterDesktop\obj\project.assets.json' }
if (-not $OutPath) { $OutPath = Join-Path $repo 'THIRD-PARTY-LICENSES.txt' }
$textsDir = Join-Path $PSScriptRoot 'license-texts'
$noticePath = Join-Path $repo 'NOTICE'

# Used only at build time; nothing from them ships.
$buildOnly = @('Microsoft.Windows.SDK.BuildTools', 'Microsoft.Windows.SDK.BuildTools.MSIX')
# Long licenses printed once at the end instead of under every package.
$sharedIds = @('Apache-2.0', 'MPL-2.0', 'MPL-1.1', 'MS-PL')
$rule = '=' * 80

if (-not (Test-Path $AssetsPath)) { throw "Not found: $AssetsPath. Run 'dotnet restore PhilterDesktop' first." }

function Read-Text([string]$Path) {
    # Normalize line endings and trim trailing blank lines so output is stable.
    $t = [IO.File]::ReadAllText($Path)
    return ($t -replace "`r`n", "`n" -replace "`r", "`n").TrimEnd()
}

$notice = Read-Text $noticePath

# The "License:" / "Copyright:" fields of a package's NOTICE entry.
function Get-NoticeField([string]$Name, [string]$Version, [string]$Field) {
    $m = [regex]::Match($notice, "(?m)^$([regex]::Escape($Name)) $([regex]::Escape($Version))\b[^\n]*\n((?:[ ].*\n?)*)")
    if (-not $m.Success) {
        # Grouped entries (e.g. the Windows App SDK family) list sub-packages by suffix.
        $suffix = $Name.Substring($Name.LastIndexOf('.'))
        $m = [regex]::Match($notice, "(?ms)^(\S[^\n]*$([regex]::Escape($suffix)) $([regex]::Escape($Version))\b.*?\n)((?:[ ].*\n?)*)")
        if (-not $m.Success) { return $null }
        $block = $m.Groups[2].Value
    } else {
        $block = $m.Groups[1].Value
    }
    $f = [regex]::Match($block, "(?m)^\s+$([regex]::Escape($Field)):\s+(.+)$")
    if ($f.Success) { return $f.Groups[1].Value.Trim() } else { return $null }
}

function Get-Template([string]$Id, [string]$Copyright) {
    $text = Read-Text (Join-Path $textsDir "$Id.txt")
    $line = if ($Copyright -match '^(?i)copyright') { $Copyright } else { "Copyright $Copyright" }
    return [regex]::Replace($text, '(?m)^Copyright \(c\) <year> <[^>]+>\.?[ \t]*$', $line.Replace('$', '$$'))
}

$assets = Get-Content -Raw $AssetsPath | ConvertFrom-Json
$packageRoot = @($assets.packageFolders.PSObject.Properties.Name)[0]
$libs = $assets.libraries.PSObject.Properties |
    Where-Object { $_.Value.type -eq 'package' } |
    ForEach-Object { $n, $v = $_.Name.Split('/'); [pscustomobject]@{ Name = $n; Version = $v; Path = $_.Value.path } } |
    Where-Object { $buildOnly -notcontains $_.Name } |
    Sort-Object { $_.Name.ToLowerInvariant() }

$seenTexts = @{}      # normalized text -> first package that printed it
$sharedUsed = New-Object System.Collections.Generic.SortedSet[string]
$sb = New-Object System.Text.StringBuilder
function Add([string]$s = '') { [void]$sb.Append($s).Append("`n") }

Add 'THIRD-PARTY LICENSES'
Add ''
Add 'Philter Desktop includes the open-source components listed below. Each is the property of its'
Add 'copyright holders and is distributed under its own license, reproduced here in full. A summary'
Add 'list is in NOTICE.txt.'
Add ''
Add 'Generated by scripts/generate-third-party-licenses.ps1; do not edit by hand.'

foreach ($lib in $libs) {
    $dir = Join-Path $packageRoot $lib.Path
    $nuspec = [xml](Get-Content -Raw (Get-ChildItem $dir -Filter *.nuspec | Select-Object -First 1).FullName)
    $meta = $nuspec.package.metadata
    $licenseNode = $meta.license
    $id = if ($licenseNode -and $licenseNode.type -eq 'expression') { $licenseNode.'#text' } else { Get-NoticeField $lib.Name $lib.Version 'License' }
    $copyright = Get-NoticeField $lib.Name $lib.Version 'Copyright'

    Add ''
    Add $rule
    Add "$($lib.Name) $($lib.Version)"
    if ($id) { Add "License: $id" }
    Add $rule
    Add ''

    # 1. A license file shipped in the package.
    $file = $null
    if ($licenseNode -and $licenseNode.type -eq 'file') { $file = Join-Path $dir $licenseNode.'#text' }
    if (-not $file -or -not (Test-Path $file)) {
        $file = Get-ChildItem $dir -File | Where-Object { $_.Name -match '^(?i)licen[cs]e(\.(txt|md))?$' } | Select-Object -First 1 -ExpandProperty FullName
    }

    if ($file) {
        $text = Read-Text $file
        if ($seenTexts.ContainsKey($text)) {
            Add "Same license text as $($seenTexts[$text]) above."
        } else {
            $seenTexts[$text] = "$($lib.Name) $($lib.Version)"
            Add $text
        }
    } elseif ($id) {
        # 2. SPDX texts: templates inline, shared licenses referenced.
        $first = $true
        foreach ($part in ($id -split '\s+(?:OR|AND)\s+')) {
            $part = $part.Trim('(', ')', ' ')
            if (-not $first) { Add ''; Add "  -- or, at your option --"; Add '' }
            $first = $false
            if ($sharedIds -contains $part) {
                [void]$sharedUsed.Add($part)
                Add "Licensed under the $part license; its full text is in the shared license texts at the end of this file."
                if ($copyright) { Add "Copyright: $copyright" }
            } elseif (Test-Path (Join-Path $textsDir "$part.txt")) {
                if (-not $copyright) { throw "$($lib.Name) $($lib.Version): $part needs a copyright line, and NOTICE has none." }
                Add (Get-Template $part $copyright)
            } else {
                # The package names its license only by URL (no text is shipped in the package).
                $url = $meta.licenseUrl
                Add "License terms: $(if ($url) { $url } else { $part })"
                if ($copyright) { Add "Copyright: $copyright" }
            }
        }
    } else {
        throw "$($lib.Name) $($lib.Version): no license file, no SPDX expression, and no License: line in NOTICE."
    }

    # 3. Notices the package ships for its own bundled components.
    $notices = Get-ChildItem $dir -File | Where-Object { $_.Name -match '^(?i)(notice|third-?party-?notices)(\.(txt|md))?$' } | Sort-Object Name
    foreach ($n in $notices) {
        $text = Read-Text $n.FullName
        Add ''
        Add "--- $($n.Name) (shipped in the package) ---"
        Add ''
        if ($seenTexts.ContainsKey($text)) {
            Add "Same text as in $($seenTexts[$text]) above."
        } else {
            $seenTexts[$text] = "$($lib.Name) $($lib.Version)"
            Add $text
        }
    }
}

# The bundled name-detection model.
Add ''
Add $rule
Add 'PhEye person-name detection model (ph-eye-pii-en-xsmall)'
Add 'License: CC-BY-4.0'
Add $rule
Add ''
Add 'Copyright: Philterd, LLC. https://huggingface.co/philterd/ph-eye-pii-en-xsmall'
Add 'Trained on the NVIDIA Nemotron-PII dataset (https://huggingface.co/datasets/nvidia/Nemotron-PII),'
Add 'licensed CC-BY-4.0 by NVIDIA Corporation. Fine-tuned from microsoft/deberta-v3-xsmall (MIT) with the'
Add 'GLiNER architecture (https://github.com/urchade/GLiNER, Apache-2.0).'
Add ''
Add (Read-Text (Join-Path $textsDir 'CC-BY-4.0.txt'))
[void]$sharedUsed.Add('Apache-2.0')

# Shared license texts.
Add ''
Add $rule
Add 'SHARED LICENSE TEXTS'
Add $rule
foreach ($sid in $sharedUsed) {
    $path = if ($sid -eq 'Apache-2.0') { Join-Path $repo 'PhilterDesktop\Resources\apache-license.txt' } else { Join-Path $textsDir "$sid.txt" }
    Add ''
    Add "--- $sid ---"
    Add ''
    Add (Read-Text $path)
}

$output = $sb.ToString().Replace("`n", "`r`n")
$encoding = New-Object System.Text.UTF8Encoding($true)

if ($Check) {
    $current = if (Test-Path $OutPath) { [IO.File]::ReadAllText($OutPath) } else { '' }
    if ($current -ne $output) {
        [Console]::Error.WriteLine("THIRD-PARTY-LICENSES.txt is out of date. Run scripts\generate-third-party-licenses.ps1 and commit the result.")
        exit 1
    }
    Write-Host 'THIRD-PARTY-LICENSES.txt is up to date.'
    exit 0
}

[IO.File]::WriteAllText($OutPath, $output, $encoding)
Write-Host "Wrote $OutPath ($([math]::Round($output.Length / 1KB)) KB, $(@($libs).Count) packages)."
